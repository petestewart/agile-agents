/** Glyphs drawn filled rather than stroked (a solid play/stop reads better small). */
const FILLED: ReadonlySet<IconName> = new Set<IconName>(['play', 'square']);

export function Icon({
  name,
  size = 16,
  className,
  label,
  strokeWidth = 1.75,
}: {
  name: IconName;
  size?: number;
  className?: string;
  /** Present: the icon is announced; absent: decorative (`aria-hidden`). */
  label?: string;
  strokeWidth?: number;
}): JSX.Element {
  const common = {
    className: className ? `cr-icon ${className}` : 'cr-icon',
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    fill: FILLED.has(name) ? 'currentColor' : 'none',
    stroke: 'currentColor',
    strokeWidth,
    strokeLinecap: 'round' as const,
    strokeLinejoin: 'round' as const,
    'data-icon': name,
  };
  if (label) {
    return (
      <svg {...common} role="img" aria-label={label}>
        <title>{label}</title>
        {PATHS[name]}
      </svg>
    );
  }
  return (
    <svg {...common} aria-hidden="true">
      {PATHS[name]}
    </svg>
  );
}
